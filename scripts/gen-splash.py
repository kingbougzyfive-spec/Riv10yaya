"""Generates iOS/iPadOS launch (splash) images and lib/splash.ts. Run: python3 scripts/gen-splash.py
Needs Pillow. Output is committed, so this is only re-run if the icon or colours change."""
import os
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BG = (7, 11, 20)
GLOW = (16, 185, 129)
icon = Image.open(os.path.join(ROOT, "public/icons/icon-512.png")).convert("RGBA")

# (css width, css height, pixel ratio) in portrait
DEVICES = [
    (320, 568, 2), (375, 667, 2), (414, 736, 3), (375, 812, 3), (414, 896, 2), (414, 896, 3),
    (390, 844, 3), (428, 926, 3), (393, 852, 3), (430, 932, 3), (402, 874, 3), (440, 956, 3),
    (768, 1024, 2), (810, 1080, 2), (834, 1112, 2), (820, 1180, 2), (834, 1194, 2), (1024, 1366, 2), (1032, 1376, 2),
]

def make(w, h, path):
    img = Image.new("RGB", (w, h), BG)
    glow = Image.new("RGB", (w, h), BG)
    d = ImageDraw.Draw(glow)
    r = int(min(w, h) * 0.45)
    d.ellipse((w // 2 - r, h // 2 - r, w // 2 + r, h // 2 + r), fill=GLOW)
    glow = glow.filter(ImageFilter.GaussianBlur(r * 0.55))
    img = Image.blend(img, glow, 0.22)
    size = int(min(w, h) * 0.26)
    ic = icon.resize((size, size), Image.LANCZOS)
    img.paste(ic, ((w - size) // 2, (h - size) // 2), ic)
    img.save(path, optimize=True)

entries = []
for cw, ch, pr in DEVICES:
    for orient in ("portrait", "landscape"):
        if orient == "portrait":
            pw, ph, mw, mh = cw * pr, ch * pr, cw, ch
        else:
            pw, ph, mw, mh = ch * pr, cw * pr, ch, cw
        name = f"splash-{pw}x{ph}.png"
        out = os.path.join(ROOT, "public/splash", name)
        if not os.path.exists(out):
            make(pw, ph, out)
        entries.append((name, mw, mh, pr, orient))

lines = ["// Generated by scripts/gen-splash.py. Do not edit by hand.", "export const SPLASH = ["]
for n, w, h, pr, o in entries:
    lines.append(f'  {{ src: "/splash/{n}", media: "(device-width: {w}px) and (device-height: {h}px) and (-webkit-device-pixel-ratio: {pr}) and (orientation: {o})" }},')
lines.append("] as const;")
open(os.path.join(ROOT, "lib/splash.ts"), "w").write("\n".join(lines) + "\n")
print(len(entries), "splash entries")
